/**
 * FR-R3-100 (FR-017) — what the attested gate covers is DERIVED from the script
 * chain, not typed beside it.
 *
 * THE DEFECT THIS PREVENTS. `RELEASE.md` §2a tells an operator what a release is
 * bound to. Before FR-R3-100 the binding named `npm run ci`, which did not run the
 * secret scan, the workflow-pin check, the license check, the docs check or
 * `contracts:check` — so a release could be attested past a failing secret scan while
 * a document said the gate covered the project's verification. A hand-written list of
 * what a gate covers is a claim about a script, and claims about scripts drift.
 *
 * WHAT IS DERIVED. The transitive closure of `npm run gate` over `package.json`
 * scripts: every `npm run <name>` reachable from it, plus the leaf commands that are
 * not `npm run` (a `node scripts/...`, a `vitest run`, a `playwright test`). The
 * closure is the authority; the document must state exactly it.
 *
 * WHY A CLOSURE AND NOT THE LITERAL STRING. `gate` names six things and reaches
 * roughly thirty. An operator asking "does the gate run the secret scan?" is asking
 * about the closure, and a check over the literal string would pass while the answer
 * changed underneath it.
 *
 * FAILURE IS A REFUSAL, both directions. A stage in the chain that the document does
 * not list is an undeclared check; a stage the document lists that the chain does not
 * reach is a false claim. The second is the worse one and is why this is not a
 * one-directional "document mentions everything" test.
 *
 * FR-R3-135 — the entry point is now taken from `GATE_COMMAND_SPEC`, not written here as
 * `'gate'`. This check was the other half of the same defect: it derived `RELEASE.md`'s
 * coverage block from the script name `gate` while `record-gate-run.mjs` spawned
 * `npm run ci`, so the document accurately described the closure of a command that no
 * attestation had ever observed. The derivation was sound and its subject was wrong. Sharing
 * one authority means a future change to what the gate is moves both at once; the value is
 * still `'gate'`, so no block regenerates on this change.
 */
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GATE_COMMAND_SPEC } from './gate-attestation.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const GATE_SCRIPT = GATE_COMMAND_SPEC.script;

/** The markers that fence the derived block in RELEASE.md. */
export const BLOCK_START = '<!-- BEGIN DERIVED: gate-coverage -->';
export const BLOCK_END = '<!-- END DERIVED: gate-coverage -->';

const scripts = () =>
  JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8')).scripts ?? {};

/**
 * Every script name reachable from `entry`, in first-encounter order.
 *
 * Cycles terminate on the `seen` set rather than recursing — a chain that referenced
 * itself would otherwise hang the gate, and a hanging gate is indistinguishable from
 * a slow one.
 */
export function reachableScripts(all, entry) {
  const order = [];
  const seen = new Set();
  const walk = (name) => {
    if (seen.has(name)) return;
    seen.add(name);
    order.push(name);
    const body = all[name];
    if (typeof body !== 'string') return;
    for (const match of body.matchAll(/npm run ([a-zA-Z0-9:_-]+)/g)) walk(match[1]);
  };
  walk(entry);
  return order;
}

/**
 * The checks a reader would recognise: reachable scripts whose body does real work
 * rather than only composing other scripts.
 *
 * A pure composer (`ci` is nothing but `npm run x && npm run y`) is not itself a
 * check, and listing it would tell an operator nothing about coverage.
 */
export function derivedChecks(all, entry = GATE_SCRIPT) {
  return reachableScripts(all, entry)
    .filter((name) => {
      const body = all[name];
      if (typeof body !== 'string') return false;
      const withoutRuns = body.replaceAll(/npm run [a-zA-Z0-9:_-]+/g, '').replaceAll('&&', '');
      return withoutRuns.trim().length > 0;
    })
    .sort();
}

/** The block the document must carry, generated. */
export function renderBlock(all) {
  const checks = derivedChecks(all);
  const lines = [
    BLOCK_START,
    '',
    `<!-- Generated by scripts/check-gate-coverage-parity.mjs. Do not edit by hand. -->`,
    '',
    `\`npm run ${GATE_SCRIPT}\` reaches **${checks.length}** checks that do work of their own:`,
    '',
    ...checks.map((name) => `- \`${name}\` — \`${all[name]}\``),
    '',
    BLOCK_END
  ];
  return lines.join('\n');
}

export function decideParity(documentText, all) {
  const start = documentText.indexOf(BLOCK_START);
  const end = documentText.indexOf(BLOCK_END);
  if (start === -1 || end === -1) {
    return {
      ok: false,
      reason: 'block-missing',
      message:
        `RELEASE.md carries no derived gate-coverage block. Insert ${BLOCK_START} … ` +
        `${BLOCK_END} and run this script with --write.`
    };
  }
  const actual = documentText.slice(start, end + BLOCK_END.length);
  const expected = renderBlock(all);
  if (actual.trim() !== expected.trim()) {
    return {
      ok: false,
      reason: 'drifted',
      message:
        'RELEASE.md §2a no longer states what `npm run gate` actually reaches. The chain is ' +
        'the authority; regenerate with `node scripts/check-gate-coverage-parity.mjs --write`.'
    };
  }
  return { ok: true, checks: derivedChecks(all).length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const all = scripts();
  const relPath = resolve(ROOT, 'RELEASE.md');
  const text = readFileSync(relPath, 'utf8');
  if (process.argv.includes('--write')) {
    const start = text.indexOf(BLOCK_START);
    const end = text.indexOf(BLOCK_END);
    if (start === -1 || end === -1) {
      console.error('RELEASE.md carries no derived gate-coverage block to write into.');
      process.exit(1);
    }
    const { writeFileSync } = await import('node:fs');
    writeFileSync(relPath, text.slice(0, start) + renderBlock(all) + text.slice(end + BLOCK_END.length));
    console.log(`gate coverage block regenerated (${derivedChecks(all).length} checks).`);
    process.exit(0);
  }
  const verdict = decideParity(text, all);
  if (!verdict.ok) {
    console.error(`gate-coverage parity: ${verdict.reason} — ${verdict.message}`);
    process.exit(1);
  }
  console.log(`gate-coverage parity: ok (${verdict.checks} derived checks stated).`);
}
